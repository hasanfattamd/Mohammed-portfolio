import { readFile, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('../dist/', import.meta.url));
const html = await readFile(path.join(root, 'index.html'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
assert.equal(new Set(ids).size, ids.length, 'Duplicate IDs');
for (const [, target] of html.matchAll(/href="#([^"]+)"/g)) assert(ids.includes(target), `Broken anchor: ${target}`);
for (const [, asset] of html.matchAll(/(?:src|href)="(\/[^"#]*)"/g)) await access(path.join(root, asset));
const images = [...html.matchAll(/<img\b[^>]*>/g)].map(m => m[0]);
for (const img of images) assert(/alt="[^"]+"/.test(img) && /width="\d+"/.test(img) && /height="\d+"/.test(img), 'Image missing alternative text or dimensions');
assert(!html.includes('data:image/'), 'Inline mockup imagery should be extracted');
assert(!html.includes('data-lucide='), 'Unrendered icon');
assert(!html.includes('Preview pending'), 'Unfinished project preview');
assert(!html.includes('LinkedIn recommendation'), 'Testimonial source label must remain removed');
assert(!html.includes('October 21, 2023'), 'Testimonial date must remain removed');
assert.equal((html.match(/class="project-card"/g) || []).length, 5);
assert.equal((html.match(/class="macbook"/g) || []).length, 5);
assert.equal((html.match(/class="iphone"/g) || []).length, 5);
assert.equal((html.match(/class="step"/g) || []).length, 5);
assert.equal((html.match(/<li>/g) || []).length, 34);
assert(html.includes('mailto:hasanfattamd@gmail.com'));
assert(html.includes('https://www.linkedin.com/in/hasanfattamd/'));
assert(html.includes('https://epictoursgrancanaria.com/'));
console.log('Checks passed: all local assets and anchors resolve; five complete project cards, five process phases, 34 skills, correct contact links and testimonial.');
